"""Package only browser runtime dependencies for GitHub Pages."""

import hashlib
import json
import os
from pathlib import Path
import re
import shutil


ROOT = Path(__file__).resolve().parent.parent
OUTPUT = (ROOT / "dist").resolve()
MARKER = ".megachonk-build"
STATIC_FILES = (
    "index.html", "styles.css", "credits.html",
    "assets/models/turkish-van-game-cat.glb",
    "assets/models/source/jonas-dichelle-cat/ATTRIBUTION.md",
    "assets/models/source/jonas-dichelle-cat/LICENSE.html",
    "vendor/three/LICENSE",
)
IMPORTS = re.compile(r"\b(?:import|export)\s+(?:[^;'\"]*?\s+from\s+)?['\"]([^'\"]+)['\"]")
DYNAMIC_IMPORTS = re.compile(r"\bimport\s*\(\s*['\"]([^'\"]+)['\"]")


def project_file(path):
    resolved = path.resolve()
    if not resolved.is_relative_to(ROOT) or not resolved.is_file():
        raise RuntimeError(f"Missing or unsafe runtime dependency: {path}")
    return resolved


def module_dependencies():
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    match = re.search(r'<script\s+type="importmap">(.*?)</script>', html, re.S)
    if not match:
        raise RuntimeError("index.html has no import map")
    imports = json.loads(match.group(1))["imports"]
    visited = set()
    pending = [ROOT / "game.js"]
    while pending:
        module = project_file(pending.pop())
        if module in visited:
            continue
        visited.add(module)
        source = module.read_text(encoding="utf-8")
        for specifier in set(IMPORTS.findall(source) + DYNAMIC_IMPORTS.findall(source)):
            if specifier.startswith("."):
                dependency = module.parent / specifier
            elif specifier in imports:
                dependency = ROOT / imports[specifier]
            else:
                prefix = next((key for key in imports if key.endswith("/") and specifier.startswith(key)), None)
                if prefix is None:
                    raise RuntimeError(f"Unmapped import {specifier!r} in {module.name}")
                dependency = ROOT / imports[prefix] / specifier[len(prefix):]
            pending.append(dependency)
    return visited


def main():
    # Never recursively clear an arbitrary caller-supplied directory.
    if OUTPUT.parent != ROOT or OUTPUT.name != "dist":
        raise RuntimeError("Build output must be the project's dist directory")
    if OUTPUT.exists():
        if not (OUTPUT / MARKER).is_file():
            raise RuntimeError("Refusing to replace an unrecognized dist directory")
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    (OUTPUT / MARKER).write_text("Generated by tools/build_pages.py\n", encoding="ascii")
    (OUTPUT / ".nojekyll").touch()
    files = {project_file(ROOT / name) for name in STATIC_FILES} | module_dependencies()
    manifest = {"revision": os.environ.get("GITHUB_SHA", "local"), "files": {}}
    for source in sorted(files):
        relative = source.relative_to(ROOT)
        target = OUTPUT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        data = source.read_bytes()
        manifest["files"][relative.as_posix()] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    (OUTPUT / "build-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    size = sum(item["bytes"] for item in manifest["files"].values())
    print(f"Built {len(files)} runtime files ({size / 1_000_000:.2f} MB) in dist/")


if __name__ == "__main__":
    main()
