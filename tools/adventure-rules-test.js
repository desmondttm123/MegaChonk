const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const load = (file) => import(`data:text/javascript;base64,${fs.readFileSync(path.join(__dirname, "..", file)).toString("base64")}`);

(async () => {
  const { RunProgress, BossEncounter, BOSS_DEFINITIONS } = await load("adventure-rules.js");
  const { assessJump, getJumpProfile } = await load("jump-rules.js");
  const progress = new RunProgress();
  assert.equal(progress.equip({ id: "c1", kind: "collar", tier: 2 }), true);
  progress.equip({ id: "p1", kind: "charm", tier: 2 });
  assert.equal(progress.stats.clawDamage, 2);
  assert.equal(progress.stats.speed, 1.06);
  assert.equal(progress.stats.hungerDrain, 0.8);
  assert.equal(progress.equip({ id: "p1", kind: "charm", tier: 2 }), false);
  assert.equal(progress.die(), true);
  assert.equal(progress.charm, null);
  assert.equal(progress.collar.tier, 2);
  assert.equal(progress.stats.clawDamage, 1);
  assert.equal(progress.equip({ id: "p1", kind: "charm", tier: 2 }), false, "Death must not respawn already claimed charms");
  progress.equip({ id: "c0", kind: "collar", tier: 1 });
  assert.equal(progress.collar.tier, 2, "Weaker equipment must not downgrade a slot");
  const boss = new BossEncounter();
  const rear = { x: 0, z: -4.3, y: 0, heading: 0 };
  const front = { x: 0, z: 0.3, y: 0, heading: Math.PI };
  assert.equal(boss.strike(front).reason, "armored-front");
  assert.equal(boss.strike(rear, "Bite").reason, "claws-only");
  assert.equal(boss.strike({ ...rear, heading: Math.PI }).reason, "face-target");
  assert.equal(boss.strike({ ...rear, z: -8 }).reason, "range");
  assert.equal(boss.strike(rear, "Claw", 2).hit, true);
  assert.equal(boss.health, 6);
  assert.equal(boss.strike(rear).hit, false, "Repeated damage in one swing must not count");
  boss.phaseIndex = 2;
  assert.equal(boss.update(0.1, rear).length, 0, "Suction must not catch a cat behind the boss");
  assert.ok(boss.update(0.1, front).some((event) => event.type === "pull"));
  assert.ok(boss.update(0.15, front).some((event) => event.type === "caught"));
  assert.equal(boss.update(0.1, { ...front, y: 1.2 }).length, 0, "A correctly timed jump can clear the intake");
  boss.phaseIndex = 1;
  assert.equal(boss.update(0.1, front).length, 0, "Warning must not deal untelegraphed damage");
  for (let life = 0; life < 8; life++) { boss.loseLife(); assert.equal(boss.status, "active"); }
  boss.loseLife();
  assert.equal(boss.lives, 0);
  assert.equal(boss.status, "retry");
  assert.equal(boss.health, 6, "Damage remains across the nine lives, not across retries");
  assert.equal(boss.strike(rear).hit, false);
  boss.reset();
  assert.equal(boss.health, 8);
  assert.equal(boss.lives, 9);
  boss.phaseIndex = 3;
  for (let strike = 0; strike < 8; strike++) { boss.hitCooldown = 0; boss.strike(rear); }
  assert.equal(boss.status, "defeated", "Fight must remain winnable with no pendant");
  assert.deepEqual(boss.update(1, front), []);
  let customAttacks = 0;
  const custom = new BossEncounter({ ...BOSS_DEFINITIONS.vacuum, phases: [{ id: "custom", duration: 2, attack: "pulse" }] }, { pulse: () => { customAttacks++; return []; } });
  custom.update(0.1, rear);
  assert.equal(customAttacks, 1, "Additional boss attack handlers must be pluggable");
  const differentWeakPoint = new BossEncounter({ ...BOSS_DEFINITIONS.vacuum, weakPoint: "open" }, undefined, { open: () => null });
  assert.equal(differentWeakPoint.strike(front, "Bite").hit, true, "A future boss can have a different vulnerability without changing the vacuum");
  for (const rise of [0.32, 0.52, 0.68, 0.74]) assert.equal(assessJump({ rise }).allowed, true);
  assert.equal(assessJump({ rise: 2 }).allowed, false);
  assert.equal(assessJump({ gap: 20 }).allowed, false);
  assert.equal(getJumpProfile(5, 48, true).allowed, false);
  assert.equal(getJumpProfile(60, 95, true).allowed, false);
  progress.reset();
  assert.equal(progress.collar, null);
  assert.equal(progress.deaths, 0);
  console.log("Adventure rules passed: equipment/death, rear-only claws, suction, nine lives/retry, bare-paw victory, custom attacks, safe jump envelope");
})().catch((error) => { console.error(error); process.exitCode = 1; });
