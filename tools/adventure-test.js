const assert = require("assert/strict");
const { chromium } = require("playwright");
const { spawn } = require("child_process");
const path = require("path");
const captureScreenshot = require("./capture-screenshot");
const defeatVacuum = require("./boss-driver");
const root = path.resolve(__dirname, "..");

(async () => {
  const server = spawn("python", ["-m", "http.server", "4181", "--bind", "127.0.0.1"], { cwd: root, stdio: "ignore", windowsHide: true });
  let browser;
  const errors = [];
  try {
    browser = await chromium.launch({ headless: true, executablePath: "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe" });
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    page.on("pageerror", (e) => errors.push(e.message));
    page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
    await new Promise((r) => setTimeout(r, 500));
    await page.goto("http://127.0.0.1:4181", { waitUntil: "networkidle" });
    await page.waitForFunction(() => window.__megaChonk?.state.ready);
    await page.evaluate(() => { window.__megaChonk.regenerate(424242); window.__megaChonk.start(); });
    await page.waitForFunction(() => !window.__megaChonk.state.transitioning);
    const snapshot = () => page.evaluate(() => window.__megaChonk.snapshot());
    const place = (x, z, heading = 0) => page.evaluate(({ x, z, heading }) => {
      const { character, state } = window.__megaChonk;
      character.root.position.set(x, 0, z);
      character.velocity.set(0, 0, 0);
      character.verticalVelocity = 0;
      character.heading = heading;
      character.root.rotation.y = heading;
      state.grounded = true;
      state.forcedAction = null; state.actionTime = 0; state.jumpBuffer = 0;
      state.sitting = false; state.invulnerable = 0;
    }, { x, z, heading });
    for (const item of (await snapshot()).adventure.items) { await place(item.x, item.z); await page.waitForTimeout(100); }
    let s = await snapshot();
    assert.equal(s.adventure.collar.tier, 1);
    assert.equal(s.adventure.charm.tier, 1);
    assert.equal(await page.evaluate(() => window.__megaChonk.character.collar.visible && window.__megaChonk.character.pendant.visible), true);
    await page.waitForTimeout(650);
    await captureScreenshot(page, { path: path.join(root, "assets/previews/mega-chonk-equipment.png") });
    let foodEnemy = s.adventure.enemies[0];
    const beforeSnack = await snapshot();
    await place(foodEnemy.x, foodEnemy.z - 1.0);
    await page.keyboard.press("f");
    await page.waitForTimeout(420);
    let foodDrop = (await snapshot()).adventure.items.find((item) => item.kind === "food");
    assert.ok(foodDrop, "Food-drop enemy must create a snack pickup");
    await place(foodDrop.x, foodDrop.z);
    await page.waitForTimeout(100);
    const afterSnack = await snapshot();
    assert.ok(Math.abs(afterSnack.satiety - Math.min(100, beforeSnack.satiety + 10)) < 0.2);
    assert.ok(afterSnack.chonk > beforeSnack.chonk + 8.8);
    assert.equal(afterSnack.snackPoints, beforeSnack.snackPoints + 25);
    await place(foodDrop.x, foodDrop.z);
    await page.waitForTimeout(100);
    assert.equal((await snapshot()).snackPoints, afterSnack.snackPoints, "A collected drop must not grant its reward twice");
    await page.waitForTimeout(400);
    await page.evaluate(() => window.__megaChonk.loadLevel(1));
    assert.equal((await snapshot()).adventure.charm.tier, 1, "Equipment must carry between rooms");
    let enemy = (await snapshot()).adventure.enemies[0];
    await place(enemy.x, enemy.z - 0.85);
    await page.waitForTimeout(180);
    await captureScreenshot(page, { path: path.join(root, "assets/previews/mega-chonk-clockwork-mouse.png") });
    await page.keyboard.press("f");
    await page.waitForTimeout(420);
    s = await snapshot();
    assert.equal(s.adventure.kills, 2);
    const drop = s.adventure.items.find((item) => item.id.includes("-loot"));
    assert.equal(drop.kind, "charm", "Every enemy kill must drop a reward");
    await place(drop.x, drop.z);
    await page.waitForTimeout(100);
    assert.equal((await snapshot()).adventure.charm.tier, 2);
    enemy = (await snapshot()).adventure.enemies.find((e) => e.active);
    await place(enemy.x, enemy.z);
    await page.waitForFunction(() => window.__megaChonk.adventureSnapshot().deaths === 1, null, { timeout: 3000 });
    s = await snapshot();
    assert.equal(s.adventure.charm, null);
    assert.equal(s.adventure.collar.tier, 1);
    console.log("Equipment carry, enemy telegraph/kill/loot, death and charm loss passed");
    await page.evaluate(() => window.__megaChonk.restart());
    await page.waitForFunction(() => !window.__megaChonk.state.transitioning);
    await page.evaluate(() => window.__megaChonk.regenerate(424242));
    assert.equal((await snapshot()).adventure.stats.speed, 1, "Jump checks must not rely on equipment bonuses");

    const jumps = [];
    for (const level of [0, 1, 2]) {
      await page.evaluate((level) => { window.__megaChonk.loadLevel(level); window.__megaChonk.setCondition(38, 75); }, level);
      const obstacle = await page.evaluate(() => window.__megaChonk.navigation().generation.obstacles.filter((o) => o.type === "hurdle").sort((a, b) => b.height - a.height)[0]);
      assert.equal(obstacle.jump.allowed, true);
      await place(obstacle.x, obstacle.z + 2.05, Math.PI);
      await page.evaluate(() => { window.__megaChonk.state.yaw = 0; window.__megaChonk.state.invulnerable = 3; });
      await page.keyboard.down("Shift");
      await page.keyboard.down("w");
      await page.waitForFunction((z) => window.__megaChonk.character.root.position.z < z + 1.25, obstacle.z, { timeout: 2500 });
      await page.keyboard.press("Space");
      await page.waitForFunction((z) => window.__megaChonk.character.root.position.z < z - 0.65, obstacle.z, { timeout: 2500 });
      await page.keyboard.up("w");
      await page.keyboard.up("Shift");
      await page.waitForFunction(() => window.__megaChonk.state.grounded, null, { timeout: 3000 });
      jumps.push({ level: level + 1, height: obstacle.height, cleared: true });
    }
    console.log(`Actual conservative-condition hurdle jumps passed: ${JSON.stringify(jumps)}`);
    const bossCollar = (await snapshot()).adventure.items.find((item) => item.kind === "collar" && item.active);
    await place(bossCollar.x, bossCollar.z);
    await page.waitForTimeout(100);
    const bossCharm = (await snapshot()).adventure.items.find((item) => item.kind === "charm" && item.active);
    await place(bossCharm.x, bossCharm.z);
    await page.waitForTimeout(100);
    assert.equal((await snapshot()).adventure.charm.tier, 3);
    await page.evaluate(() => window.__megaChonk.completeLevel());
    await page.waitForFunction(() => window.__megaChonk.state.stage === "boss" && !window.__megaChonk.state.transitioning, null, { timeout: 6000 });
    assert.equal((await snapshot()).adventure.boss.health, 8, "Third room gate must start the boss instead of completing the game");
    await page.waitForTimeout(650);
    await captureScreenshot(page, { path: path.join(root, "assets/previews/mega-chonk-vacuum-boss.png") });
    await page.evaluate(() => window.__megaChonk.bossScenario({ phase: "recover" }));
    await place(0, 0.3, Math.PI);
    await page.keyboard.press("f");
    await page.waitForTimeout(350);
    assert.equal((await snapshot()).adventure.boss.health, 8, "Front-facing claws must not damage armor");
    await page.evaluate(() => window.__megaChonk.bossScenario({ phase: "recover" }));
    await place(0, -4.3);
    await page.keyboard.press("e");
    await page.waitForTimeout(350);
    assert.equal((await snapshot()).adventure.boss.health, 8, "Bites must not bypass the claw-only weak point");
    await page.evaluate(() => window.__megaChonk.bossScenario({ phase: "recover" }));
    await place(0, -4.3);
    await page.keyboard.press("f");
    await page.waitForTimeout(350);
    assert.equal((await snapshot()).adventure.boss.health, 6, "A rear-facing equipped claw must deal two damage at animation impact time");
    for (let lives = 9; lives > 0; lives--) {
      await page.evaluate((lives) => window.__megaChonk.bossScenario({ phase: "inhale", lives, health: 6 }), lives);
      await place(0, 0.3, Math.PI);
      await page.waitForFunction((remaining) => window.__megaChonk.adventureSnapshot().boss.lives === remaining, lives - 1, { timeout: 2500 });
      assert.equal((await snapshot()).adventure.boss.health, 6, "Suction loss should preserve damage within an attempt");
      assert.equal((await snapshot()).adventure.charm, null, "Suction death removes the pendant");
      assert.equal((await snapshot()).adventure.collar.tier, 3, "Suction death retains the collar");
    }
    await page.locator("#boss-retry").waitFor({ state: "visible" });
    assert.equal((await snapshot()).adventure.boss.status, "retry");
    await page.waitForTimeout(650);
    await captureScreenshot(page, { path: path.join(root, "assets/previews/mega-chonk-boss-retry.png") });
    await page.click("#retry-boss");
    assert.equal((await snapshot()).adventure.boss.lives, 9);
    assert.equal((await snapshot()).adventure.boss.health, 8);
    assert.equal((await snapshot()).adventure.collar.tier, 3);
    assert.equal((await snapshot()).adventure.charm, null);
    console.log("Boss front/rear/claw checks and nine-loss fight retry passed");
    const fight = await defeatVacuum(page);
    console.log(`Pendant-free boss keyboard autoplay: ${JSON.stringify(fight)}`);
    await page.waitForFunction(() => window.__megaChonk.state.gameComplete);
    assert.equal((await snapshot()).adventure.bossDefeated, true);
    assert.deepEqual(errors, []);
    await page.click("#restart-game");
    assert.equal((await snapshot()).adventure.collar, null);
    assert.equal((await snapshot()).adventure.charm, null);
    assert.equal((await snapshot()).stage, "rooms");
    await page.evaluate(() => window.__megaChonk.startBoss());
    await page.waitForFunction(() => !window.__megaChonk.state.transitioning);
    assert.equal((await snapshot()).adventure.stats.speed, 1);
    assert.equal((await snapshot()).adventure.stats.clawDamage, 1);
    const noGearFight = await defeatVacuum(page);
    await page.waitForFunction(() => window.__megaChonk.state.gameComplete);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ jumps, fight, noGearFight, bossCompletion: true, freshRunReset: true, errors }, null, 2));
    console.log("Adventure integration passed");
  } finally { if (browser) await browser.close(); server.kill(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
